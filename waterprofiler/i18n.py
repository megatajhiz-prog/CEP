class Translator:
    def __init__(self, lang: str = "fa"):
        self.lang = lang

    @property
    def rtl(self) -> bool:
        return self.lang == "fa"

    def __call__(self, key: str, **kw) -> str:
        entry = _STR.get(key)
        if entry is None:
            return key
        s = entry.get(self.lang) or entry["en"]
        return s.format(**kw) if kw else s


def all_keys():
    return list(_STR)


def missing_translations():
    return [k for k, v in _STR.items() if "fa" not in v or "en" not in v]
